/**
 * Читаемое имя профиля предметной области.
 *
 * Сервер хранит профиль внутренним ключом (general, tax, legal), и показывать
 * его как есть — значит показывать латиницу в таджикском и русском интерфейсе.
 * Функция общая для списка блокнотов и шапки блокнота: один и тот же профиль
 * они обязаны называть одинаково, иначе пользователь решит, что это разные
 * настройки.
 *
 * Незнакомый ключ возвращаем как есть: сервер вправе завести профиль раньше,
 * чем о нём узнает словарь, а прочерк вместо него скрыл бы настройку блокнота.
 */
export const resolveDomainProfileLabel = (value, t) => {
    if (!value) return '';

    const key = `notebooksPage.profiles.${value}`;
    const translated = t(key);

    return translated === key ? value : translated;
};
