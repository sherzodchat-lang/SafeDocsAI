"""Рубрики таджикского корпуса: приведение редакционных разделов к одному списку.

Откуда берётся разметка. У каждой статьи собранного корпуса есть раздел сайта —
`section`. Это метка, поставленная человеком-редактором, а не выведенная нами, и
именно она делает корпус измеримым: по ней считаются чистота и ARI на том самом
жанре и языке, которым система и занимается. Прежний размеченный набор
(task1_multilingual_dataset) остаётся измерительным прибором для алгоритма, но
он собран из Википедии и синтетики — на вопрос «а как оно на законах и паёмах»
он не отвечал вовсе.

Почему нужна нормализация, а не «берём section как есть». Четыре сайта называют
одно и то же по-разному: khovar пишет «Иқтисодӣ», jumhuriyat и ozodi —
«Иқтисод», Википедия — «иқтисод» со строчной. Без сведения это три разных
класса, и ARI померил бы не тему, а редакционную привычку.

Почему таблица написана руками, а не выведена автоматически. Сведение рубрик —
это решение о том, что считать одной темой, и оно должно быть видимым и
оспоримым на защите. Автоматическое склеивание «по похожести названий» приняло
бы те же решения молча, и объяснить их было бы нечем.

ЧТО СВЕДЕНО И ПОЧЕМУ — каждое решение названо в комментарии у своей строки.
Общее правило одно: рубрика, в которой меньше нескольких десятков документов,
кластером стать не может физически, и её приходится либо присоединять к
близкой по смыслу, либо исключать из измерения. Исключение — не выбрасывание:
документ остаётся в обучении, он просто не участвует в подсчёте метрик, потому
что его метка ничего не значит («Хабарҳо» — это «Новости», то есть весь сайт).
"""

