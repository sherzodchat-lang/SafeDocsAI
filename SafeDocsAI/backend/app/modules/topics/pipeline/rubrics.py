# Гомоглифы: буквы, которые выглядят как кириллические, но записаны латиницей.
# В корпусе такое есть: ozodi пишет рубрику «Ҷомeа» с ЛАТИНСКОЙ e (U+0065)
# вместо кириллической е (U+0435). Без этой замены «Ҷомeа» и «Ҷомеа» —
# разные строки, и одна рубрика из 203 документов развалилась бы на две, а
# заметить это было бы нечем: на экране они выглядят одинаково.
HOMOGLYPHS = str.maketrans(
    {
        "a": "а",
        "c": "с",
        "e": "е",
        "o": "о",
        "p": "р",
        "x": "х",
        "y": "у",
        "A": "А",
        "B": "В",
        "C": "С",
        "E": "Е",
        "H": "Н",
        "K": "К",
        "M": "М",
        "O": "О",
        "P": "Р",
        "T": "Т",
        "X": "Х",
    }
)


def _canonical(raw: str) -> str:
    """Приведение раздела к ключу таблицы: пробелы, регистр, гомоглифы.

    Замена гомоглифов применяется ТОЛЬКО к строкам, где кириллица уже есть.
    Иначе честно латинское название раздела (у sputnik попадается «Tajikistan
    style») превратилось бы в мешанину, и в отчёте о непокрытых разделах оно
    выглядело бы как испорченное нами, а не как то, что на сайте написано.
    """
    text = " ".join(str(raw or "").split()).lower()
    if any("а" <= letter <= "я" or letter in "ёқғҳҷӣӯ" for letter in text):
        return text.translate(HOMOGLYPHS)
    return text


