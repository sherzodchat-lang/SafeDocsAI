# Без этого таблица молча промахивается на смешанных строках. Пример из корпуса:
# «Энергетический проект CASA-1000» — кириллица вперемешку с латиницей. Замена
# гомоглифов применяется, потому что кириллица есть, и латинское «casa»
# превращается в «саsа»; ключ, записанный латиницей, перестаёт совпадать, и
# документы уходят в «без рубрики» без единого признака ошибки.
#
# Канонизация ключей на месте, а не требование «пишите ключи правильно»:
# правильность тут неочевидна даже автору таблицы, а промах не виден никак.
RAW_TO_RUBRIC = {_canonical(key): value for key, value in RAW_TO_RUBRIC.items()}
CURATED_TO_RUBRIC = {_canonical(key): value for key, value in CURATED_TO_RUBRIC.items()}
SUBJECT_TO_RUBRIC = {_canonical(key): value for key, value in SUBJECT_TO_RUBRIC.items()}
IGNORED_SECTIONS = frozenset(_canonical(key) for key in IGNORED_SECTIONS)


def normalize_section(raw: str) -> str | None:
    """Код рубрики, `UNLABELLED` для заведомо бессмысленных разделов, None — для
    неизвестных.

    Три исхода, а не два. «Неизвестный раздел» и «раздел, который решено не
    считать темой» — разные состояния: первое требует решения человека и должно
    быть названо в отчёте, второе решение уже получило. Свести их к одному
    значению значило бы позволить новому разделу сайта тихо просочиться в
    корзину.
    """
    key = _canonical(raw)
    if key in IGNORED_SECTIONS:
        return UNLABELLED
    # Редакционная рубрика имеет приоритет над нашей тематической подборкой:
    # прочитанное у редактора всегда весомее решённого нами.
    return RAW_TO_RUBRIC.get(key) or SUBJECT_TO_RUBRIC.get(key) or CURATED_TO_RUBRIC.get(key)


def rubric_names(code: str) -> tuple[str, str]:
    """Названия рубрики (таджикское, русское). Для `UNLABELLED` — свои."""
    if code == UNLABELLED:
        return UNLABELLED_TG, UNLABELLED_RU
    rubric = RUBRIC_BY_CODE.get(code)
    if rubric is None:
        raise KeyError(f"неизвестный код рубрики {code!r}")
    return rubric.tg, rubric.ru
