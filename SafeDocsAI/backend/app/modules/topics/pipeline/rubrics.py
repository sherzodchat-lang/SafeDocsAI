# Разделы, которые ЕСТЬ и которые сознательно не значат темы. Перечислены
# поимённо, а не отсеиваются по остаточному принципу: иначе новый раздел сайта
# молча попал бы в эту корзину вместо того, чтобы потребовать решения.
IGNORED_SECTIONS: frozenset[str] = frozenset(
    {
        "хабарҳо",  # «Новости» — то есть весь сайт
        "мақолаҳо",  # «Статьи» — жанр, а не тема
        "",  # раздела не было вовсе
    }
)

# Гомоглифы: буквы, которые выглядят как кириллические, но записаны латиницей.
# В корпусе такое есть: ozodi пишет рубрику «Ҷомeа» с ЛАТИНСКОЙ e (U+0065)
# вместо кириллической е (U+0435). Без этой замены «Ҷомeа» и «Ҷомеа» —
# разные строки, и одна рубрика из 203 документов развалилась бы на две, а
# заметить это было бы нечем: на экране они выглядят одинаково.
HOMOGLYPHS = str.maketrans(
    {
        "a": "а",
        "c": "с",
        "e": "е",
        "o": "о",
        "p": "р",
        "x": "х",
        "y": "у",
        "A": "А",
        "B": "В",
        "C": "С",
        "E": "Е",
        "H": "Н",
        "K": "К",
        "M": "М",
        "O": "О",
        "P": "Р",
        "T": "Т",
        "X": "Х",
    }
)


def _canonical(raw: str) -> str:
    """Приведение раздела к ключу таблицы: пробелы, регистр, гомоглифы.

    Замена гомоглифов применяется ТОЛЬКО к строкам, где кириллица уже есть.
    Иначе честно латинское название раздела (у sputnik попадается «Tajikistan
    style») превратилось бы в мешанину, и в отчёте о непокрытых разделах оно
    выглядело бы как испорченное нами, а не как то, что на сайте написано.
    """
    text = " ".join(str(raw or "").split()).lower()
    if any("а" <= letter <= "я" or letter in "ёқғҳҷӣӯ" for letter in text):
        return text.translate(HOMOGLYPHS)
    return text


def normalize_section(raw: str) -> str | None:
    """Код рубрики, `UNLABELLED` для заведомо бессмысленных разделов, None — для
    неизвестных.

    Три исхода, а не два. «Неизвестный раздел» и «раздел, который решено не
    считать темой» — разные состояния: первое требует решения человека и должно
    быть названо в отчёте, второе решение уже получило. Свести их к одному
    значению значило бы позволить новому разделу сайта тихо просочиться в
    корзину.
    """
    key = _canonical(raw)
    if key in IGNORED_SECTIONS:
        return UNLABELLED
    # Редакционная рубрика имеет приоритет над нашей тематической подборкой:
    # прочитанное у редактора всегда весомее решённого нами.
    return RAW_TO_RUBRIC.get(key) or CURATED_TO_RUBRIC.get(key)


def rubric_names(code: str) -> tuple[str, str]:
    """Названия рубрики (таджикское, русское). Для `UNLABELLED` — свои."""
    if code == UNLABELLED:
        return UNLABELLED_TG, UNLABELLED_RU
    rubric = RUBRIC_BY_CODE.get(code)
    if rubric is None:
        raise KeyError(f"неизвестный код рубрики {code!r}")
    return rubric.tg, rubric.ru
