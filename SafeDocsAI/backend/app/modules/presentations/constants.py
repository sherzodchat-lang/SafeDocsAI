# --- Ретривал ------------------------------------------------------------
#
# Сколько чанков уходит в промпт одного слайда.
#
# Своя константа, а НЕ runtime-настройка retrieval_top_k: та тюнится под чат,
# где пользователь правит её ради качества ответа на вопрос. Презентация делает
# по вызову ретривала на каждую секцию, и чужая настройка меняла бы и длину
# промпта, и время генерации всей джобы — то есть PRESENTATION_JOB_TIMEOUT,
# посчитанный по замерам, переставал бы соответствовать реальности от правки в
# админке.
SLIDE_RETRIEVAL_TOP_K = 5
# Пул кандидатов, из которого отбирается финальная пятёрка. Фиксирован по той
# же причине и намеренно равен умолчанию чатовского retrieval_top_k (20,
# app/shared/settings/runtime_settings.py): одинаковая механика легче
# диагностируется — расхождение выдачи между чатом и презентацией по одному и
# тому же блокноту будет означать разницу в запросе, а не в размере пула.
SLIDE_RETRIEVAL_CANDIDATE_POOL = 20
# Обзорная выборка под план: модель должна увидеть, о чём вообще блокнот,
# прежде чем делить его на секции.
PLAN_RETRIEVAL_TOP_K = 8

# --- Окно модели ---------------------------------------------------------
#
# Modelfile'ы стенда пиннят num_ctx (gemma4:26b — 12000), и пайплайн держится
# того же значения. Настроечное chat_model_num_ctx (умолчание 20000) здесь не
# при чём: в проде действует меньшее из двух, и считать бюджет по большему
# значит однажды молча потерять хвост промпта.
PRESENTATION_NUM_CTX = 12000

# Оценка «знаков на токен» для кириллицы — та же, что у чанкера
# (HybridChunker.CHARS_PER_TOKEN). Все расчёты бюджета ниже идут через неё.
CHARS_PER_TOKEN = 3.6

# Предел длины описания презентации (запроса пользователя «о чём колода»).
#
# Считается из бюджета ПЛАН-вызова той же методикой, что предел вопроса в
# app/api/deps.py (QUESTION_MAX_LENGTH). Числа — из кода, не на глаз.
#
# Окно: 12 000 токенов = 43 200 знаков при 3.6 знака на токен.
# Из него вычитается всё, что в план-вызов входит помимо описания:
#
#   * системный промпт плана — 1 173 знака ≈ 330 токенов (измерено на
#     build_plan_messages при 18 секциях, prompts.py);
#   * обзорная выборка — PLAN_RETRIEVAL_TOP_K = 8 чанков по max_tokens = 800
#     (HybridChunker) = 6 400 токенов, плюс XML-обвязка <chunk> с именем файла
#     ≈ 200 знаков на чанк ≈ 450 токенов -> 6 850;
#   * имя блокнота — TITLE_MAX_LENGTH = 255 знаков ≈ 70 токенов;
#   * ответ модели — title 120 знаков плюс 18 секций (максимум: SLIDE_COUNT_MAX
#     минус два слайда рендерера) по heading 80 + search_query 200 + синтаксис
#     ≈ 40 -> ≈ 6 000 знаков ≈ 1 670 токенов;
#   * ПОВТОРНАЯ попытка. Она получает весь исходный промпт, отвергнутый ответ
#     и текст претензии валидатора, а место под новый ответ нужно сверх того.
#     То есть ответ закладывается ДВАЖДЫ: 2 × 1 670 = 3 340 токенов, плюс
#     ≈ 60 токенов претензии.
#
# Занято: 330 + 6 850 + 70 + 3 340 + 60 ≈ 10 650 токенов. Остаётся ≈ 1 350
# токенов, то есть около 4 900 знаков. Берём 1 800 — примерно треть остатка, —
# и вот почему не всё:
#
#   1) 3.6 знака на токен — усреднение проекта, а не измерение токенизатора
#      gemma. На смеси языков, цифр и таблиц реальный токен короче, и запас
#      съедается первым же документом с числами;
#   2) описание уезжает не только в план: оно повторяется в КАЖДОМ слайд-вызове
#      рядом с дайджестом написанного, который к концу колоды сам стоит около
#      3 300 токенов (см. DIGEST_MAX_CHARS). Проверка по слайд-вызову: 350
#      (система, измерено — 1 239 знаков) + 4 280 (5 чанков по 800 токенов с
#      обвязкой) + 500 (описание) + 720 (ответ слайда 1 300 знаков, дважды) +
#      60 (претензия) + 3 330 (дайджест) ≈ 9 240 из 12 000 — влезает с запасом
#      около 23%;
#   3) описание — это запрос пользователя, а не документ. 1 800 знаков — около
#      270 слов, и всё, что длиннее, — вставленный целиком текст, который
#      вытесняет из окна собственно источники. Довод тот же, что у предела
#      вопроса к ассистенту.
DESCRIPTION_MAX = 1800

# Потолок дайджеста уже написанного (тексты буллетов предыдущих слайдов,
# см. build_written_digest в prompts.py).
#
# Без потолка дайджест растёт линейно по колоде: 17 контентных слайдов по
# SLIDE_BULLETS_MAX = 5 буллетов до SLIDE_BULLET_MAX_CHARS = 200 знаков дают
# 17 000 знаков ≈ 4 700 токенов на последнем слайде самой длинной колоды.
# Бюджет слайд-вызова это выдерживает (см. расчёт DESCRIPTION_MAX), но зависеть
# от SLIDE_COUNT_MAX он не должен: подняли потолок слайдов — и промпт молча
# начал обрезаться где-то в Ollama. 12 000 знаков ≈ 3 330 токенов, это ровно та
# оценка «2–3 тысячи токенов», на которую бюджет и считался; в них целиком
# помещаются последние 12 слайдов колоды.
#
# Когда потолок срабатывает, выбрасываются САМЫЕ РАННИЕ буллеты: соседние
# секции повторяют друг друга чаще, чем первая и последняя.
DIGEST_MAX_CHARS = 12000

# --- Очередь и таймаут ---------------------------------------------------
#
# Потолок времени на одну джобу целиком: план, ретривал каждой секции, слайды,
# рендер и запись файла.
#
# Замеры этапа 0 (10 слайдов, gemma4:26b, num_ctx 12000): худший прогон 91.5 с,
# тёплый 65.7 с; слайд — медиана 6.9 с, p90 8.5 с; план — от 5 до 27 с, где
# 27 с — загрузка модели в VRAM. То есть 600 с — это запас ×6.5 к худшему
# прогону. Запас такой большой не «на всякий случай», а по четырём известным
# неизвестным:
#
#   * мерили на трёх крошечных чанках, а в промпт уходит пять полноразмерных
#     (до 800 токенов каждый) — время генерации растёт вместе с промптом;
#   * повторная попытка не сработала НИ РАЗУ, то есть её цена в замерах не
#     представлена вовсе, а стоит она примерно второго вызова;
#   * холодная загрузка модели в VRAM — около 19 с, и она приходится на первую
#     джобу после простоя, то есть на самый заметный для пользователя случай;
#   * параллельные джобы не проверялись: очередь берёт по одной, но рядом
#     работает индексация, и GPU у них общий.
#
# Цена ошибки несимметрична. Слишком маленький таймаут убивает почти готовую
# колоду и заставляет пользователя ждать второй раз столько же; слишком
# большой — держит очередь занятой лишние минуты в редком случае. Поэтому
# берём с запасом, а не впритык.
PRESENTATION_JOB_TIMEOUT = 600

