def normalize_language(value: str | None) -> str:
    """Код языка -> каноническое значение контракта.

    Не переводчик кодов: приводит регистр и пробелы, а неизвестное значение
    отвергает. Молча подставлять русский нельзя — пользователь заказал колоду
    на языке, которого не получит, и узнает об этом из готового файла.
    """
    lowered = (value or "").strip().lower()
    if lowered not in SUPPORTED_LANGUAGES:
        raise ValueError(
            f"unsupported language {value!r}, expected one of "
            f"{', '.join(SUPPORTED_LANGUAGES)}"
        )
    return lowered


