# 17 000 знаков ≈ 4 700 токенов на последнем слайде самой длинной колоды.
# Бюджет слайд-вызова это выдерживает (см. расчёт DESCRIPTION_MAX), но зависеть
# от SLIDE_COUNT_MAX он не должен: подняли потолок слайдов — и промпт молча
# начал обрезаться где-то в Ollama. 12 000 знаков ≈ 3 330 токенов, это ровно та
# оценка «2–3 тысячи токенов», на которую бюджет и считался; в них целиком
# помещаются последние 12 слайдов колоды.
#
# Когда потолок срабатывает, выбрасываются САМЫЕ РАННИЕ буллеты: соседние
# секции повторяют друг друга чаще, чем первая и последняя.
DIGEST_MAX_CHARS = 12000

# --- Очередь и таймаут ---------------------------------------------------
#
# ЕДИНСТВЕННАЯ калибруемая величина раздела — потолок ОДНОГО вызова модели.
# Потолок джобы из неё выводится (presentation_job_timeout ниже) и числом
# нигде не записан.
#
# Почему на вызове, а не на джобе. Здесь стоял PRESENTATION_JOB_TIMEOUT = 600 —
# потолок джобы целиком, посчитанный от замеров этапа 0 (10 слайдов,
# gemma4:26b, корпус из трёх чанков: худший прогон 91.5 с, слайд — медиана
# 6.9 с, план — 5..27 с) с запасом ×6.5. У формулы на уровне джобы два изъяна,
# и оба проявились сразу:
#
#   1) она детектирует зависание только после того, как сгорит ВЕСЬ бюджет.
#      Повис вызов на втором слайде из пятнадцати — заказ умрёт через двадцать
#      минут, хотя всё, что нужно было понять, стало известно на второй минуте;
#   2) она сцеплена со скоростью модели, а модель меняют из админ-панели.
#      Смена чат-модели на gemma4:31b и рост корпуса до 714 чанков дали замеры
#      приёмки: слайд — медиана 32.3 с (было 6.9), максимум 41.07 с; план —
#      44.3..69.9 с; колода из 10 слайдов — 337.7 с, из 15 слайдов — 444.0 с.
#      Арифметика по худшим наблюдённым: 13 секций × 41.07 + план 69.9 = 604 с,
#      то есть запаса не осталось вовсе, и одна медленная секция или
#      единственная сработавшая повторная попытка выносила здоровый заказ в
#      'error'.
#
# 300 с на вызов — запас ×4.3 к худшему НАБЛЮДЁННОМУ вызову (план 69.9 с).
# Семантика ясная и не зависит от длины колоды: «один вызов модели не может
# идти дольше пяти минут».
#
# Почему запас щедрый. Цена ошибки несимметрична: слишком длинный таймаут стоит
# ровно «зависший заказ умрёт позже», слишком короткий — убивает здоровые
# заказы и заставляет пользователя ждать второй раз столько же. Ошибаться
# можно только в длинную сторону.
#
# От скорости модели эту константу не отвязать никакой формулой: следующая
# смена модели снова сдвинет замеры. Поэтому вместо предсказания —
# наблюдаемость: воркер пишет p50/p90 по вызовам модели в лог КАЖДОЙ джобы
# (CallTimings в service.py), и смену модели видно с одного взгляда, как
# стартовую строку про embedding-коллекцию.
LLM_CALL_TIMEOUT = 300

# ЭТО ЖЕ ЧИСЛО получает HTTP-клиент Ollama на пути презентаций
# (build_presentation_model_manager в service.py) — и вот почему это важно
# помнить, глядя на константу.
#
# Клиент строится в ModelManager с бюджетом settings.OLLAMA_TIMEOUT_SECONDS =
# 120 с. Пока презентации пользовались им, откалиброванные здесь 300 с были
# недостижимы в принципе: клиент сдавался на 120-й секунде и бросал ошибку
# провайдера, а wait_for вокруг вызова не срабатывал никогда. В логе приёмки
# это видно прямо: «max 120.0с» — ровное число там, где стоят замеры
# (p50 35.2с, p90 68.2с), то есть не длительность, а чужой потолок.
#
# Чатовские 120 с при этом остаются чатовскими: за чатом ждёт человек, и
# растягивать его зависший запрос впятеро ради фоновой джобы незачем. Одно
# число на два разных бюджета — и один из них всегда неверен.

# Запас поверх потолка вызова для wait_for в call_with_one_retry.
#
# Смысл запаса — очередь срабатывания, а не дополнительное время. Первым
# обязан сдаваться КЛИЕНТ: он знает, что именно не дождался, и приносит
# внятную ошибку с причиной (ExternalServiceErrorKind.TIMEOUT), которую можно
# показать пользователю и по которой можно решать, повторять ли вызов.
# asyncio.wait_for умеет только одно — снять корутину; из CancelledError не
# видно ни стадии, ни причины.
#
# Но и убирать wait_for нельзя: клиентский таймаут покрывает лишь то, что
# видит сам клиент, — ожидание ответа. Зависнуть можно и после: в разборе уже
# полученного тела, в потоке, который сервер не закрыл. Отсюда роль wait_for —
# страховка ВТОРОГО эшелона, а 30 с — ровно столько, чтобы клиент гарантированно
# успел сработать первым и его ошибка не была съедена отменой корутины.
LLM_CALL_WATCHDOG_MARGIN = 30
# Выводится, а не назначается: третьего числа в этой паре быть не должно —
# дрейфовать было бы чему.
LLM_CALL_WATCHDOG_TIMEOUT = LLM_CALL_TIMEOUT + LLM_CALL_WATCHDOG_MARGIN

# Сколько попыток бывает у одного вызова: первая и одна повторная
# (call_with_one_retry в service.py). Повтор — ОТДЕЛЬНЫЙ вызов модели со своим
# бюджетом, а не продолжение первого: он получает исходный промпт, отвергнутый
# ответ и претензию валидатора, то есть заново генерирует весь ответ. Отсюда он
# входит в потолок джобы множителем, а не слагаемым.
LLM_CALL_ATTEMPTS = 2

# Пауза перед повтором — и ТОЛЬКО после таймаута вызова.
#
# Симптом таймаута — медленность, а не поломка. На приёмке заказа 12
# (2026-08-04) Ollama вытесняла модель из памяти («predicted to exceed
# available memory, evicting») и грузила её заново: 9 с, 20.7 с, 51.9 с.
# Немедленный повтор возвращается ровно в тот же затор и сгорает так же,
# потратив второй бюджет вызова впустую — то есть повтор формально есть, а
# толку от него нет.
#
# Почему тридцать. Пауза обязана перекрывать ТИПИЧНУЮ перезагрузку (два
# наблюдения из трёх — 9 с и 20.7 с), но не худшую (51.9 с): худшую перекрывает
# сам потолок вызова. Повтор, начавшийся на тридцатой секунде затора, впереди
# имеет ещё целый LLM_CALL_TIMEOUT, и дождаться прогретой модели ему есть
# когда. Пауза длиной в худшее наблюдение была бы платой за то, что уже
# оплачено, — и превращала бы каждый повтор в минуту простоя.
#
# Почему только таймаут. У отказа СОЕДИНЕНИЯ и у невалидного JSON симптом
# другой: в первом случае отвечать некому, во втором модель ответила сразу и
# ответила мусором. Ждать там нечего, и пауза только оттянула бы момент, когда
# это станет известно, — то есть замедлила бы детект, ничего не починив.
#
# Число — обязательный член формулы потолка джобы (presentation_job_timeout
# ниже): пауза проходит под тем же потолком, что и сами вызовы, и забытая в
# формуле она делает потолок короче правды ровно на себя, помноженную на число
# повторов.
LLM_RETRY_PAUSE_AFTER_TIMEOUT = 30

# Потолок ПЕЧАТИ — то есть одного запуска headless Chrome.
#
# ВЫВОДИТСЯ, а не назначается, и вот из чего. Внешняя граница стадии рендера —
# LLM_CALL_TIMEOUT: ровно этим членом она входит в потолок джобы
# (presentation_job_timeout ниже), и стадия не имеет права занимать больше, чем
# за ней записано. Внутри этой границы эшелонов, как и у вызова модели, два:
#
#   * ПЕРВЫМ обязан сдаваться тот, кто знает причину, — сам subprocess. Он
#     приносит код возврата и хвост stderr, по которым видно, что случилось
#     (не нашёл страницу, упала вкладка, кончилась память), и он же убивает
#     зависшую группу процессов;
#   * wait_for вокруг стадии (_render_to_file в service.py) остаётся страховкой
#     ВТОРОГО эшелона — на зависание ВНЕ браузера: раскладку страницы по
#     отвалившемуся тому, чтение шаблона с мёртвого NFS. Из отменённой корутины
#     причины не видно, поэтому она и вторая.
#
# Запас между ними — тот же LLM_CALL_WATCHDOG_MARGIN, что и у вызова модели:
# смысл у него один и тот же (гарантировать очередь срабатывания), и третьему
# числу на ту же роль было бы чему дрейфовать.
RENDER_PRINT_TIMEOUT = LLM_CALL_TIMEOUT - LLM_CALL_WATCHDOG_MARGIN

# Сколько знаков stderr Chrome доезжает до пользователя в error_text.
#
# Не 500 (MAX_ERROR_TEXT), хотя место там есть: error_text режется на 500 знаках
# ЦЕЛИКОМ, вместе с причиной отказа, — и хвост, поставленный в конец полной
# длины, обрезался бы ровно там, где написано самое важное. Chrome пишет
# настоящую причину ПОСЛЕДНЕЙ строкой, поэтому берётся именно хвост, и берётся
# он с запасом под текст причины перед ним.
RENDER_STDERR_TAIL = 400


def presentation_job_timeout(slide_count: int) -> float:
    """Потолок джобы целиком — ВЫВЕДЕННЫЙ, а не назначенный.

    Считается из числа слайдов заказа:

        вызовов = 1 план + (slide_count − RENDERER_ADDED_SLIDES) секций

          вызовов × LLM_CALL_ATTEMPTS × LLM_CALL_WATCHDOG_TIMEOUT
        + вызовов × (LLM_CALL_ATTEMPTS − 1) × LLM_RETRY_PAUSE_AFTER_TIMEOUT
        + LLM_CALL_TIMEOUT                                       (стадия рендера)

    ПРАВИЛО, по которому выбран каждый член: это ВНЕШНЯЯ граница своей стадии,
    а не внутренняя, которая «обычно срабатывает первой». Разница ровно в этом
    слове «обычно» — оно означает наблюдение, а не предел.

    Так, у вызова модели границ две: клиентские LLM_CALL_TIMEOUT (300 с) и
    страховка wait_for на LLM_CALL_WATCHDOG_TIMEOUT (330 с). В норме первым
    сдаётся клиент, и формула прежде стояла на его числе. Но клиент существует
    ровно до того случая, ради которого и заведена страховка: зависание, которое
    он не видит по построению (разбор уже полученного тела, поток, который
    сервер не закрыл). В этом случае стадия честно занимает 330 с, а потолок,
    посчитанный по 300, оказывался короче правды на 30 с × число вызовов — то
    есть ошибался в ту единственную сторону, в которую ошибаться нельзя.

    Паузы повторов — второй член по тому же правилу: они проходят под этим
    потолком, как и сами вызовы. Их ЧИСЛО не назначается, а выводится из
    LLM_CALL_ATTEMPTS: повторов на вызов ровно на один меньше, чем попыток, и
    худший случай — когда каждый повтор идёт после таймаута, то есть с паузой.

    Стадия рендера — LLM_CALL_TIMEOUT, и это ВНЕШНЯЯ её граница по тому же
    правилу: под ней стоит wait_for в _render_to_file (service.py), а печать
    браузером ограничена изнутри меньшим числом (RENDER_PRINT_TIMEOUT выше),
    чтобы первым сдавался тот, кто знает причину. Дольше LLM_CALL_TIMEOUT стадия
    рендера занять не может, поэтому именно оно и входит в формулу.

    Это не обещание времени и не SLA: каждый вызов уже ограничен сам по себе,
    поэтому здоровая джоба до этого потолка не доходит в принципе — она раньше
    упрётся в потолок вызова. Он остаётся СТРАХОВКОЙ от беды, которую wait_for
    вокруг отдельного вызова не видит по построению: бесконечный цикл по
    секциям, ретривал, зациклившийся на пустой выдаче, зависшее соединение с
    PostgreSQL между стадиями. Поэтому он и щедрый: при 15 слайдах это 9960 с
    против 444 с настоящей колоды.

    Число слайдов вне продуктовых границ до сюда доезжать не должно (его
    отвергает и HTTP-слой, и сам пайплайн), но потолок обязан получиться
    положительным при любом входе: wait_for с отрицательным таймаутом снимает
    джобу мгновенно, то есть подменяет понятный отказ «число слайдов вне
    границ» на невнятный generation_timeout.
    """
    sections = max(1, content_section_count(slide_count))
    calls = 1 + sections
    model_calls = calls * LLM_CALL_ATTEMPTS * LLM_CALL_WATCHDOG_TIMEOUT
    retry_pauses = (
        calls * (LLM_CALL_ATTEMPTS - 1) * LLM_RETRY_PAUSE_AFTER_TIMEOUT
    )
    return float(model_calls + retry_pauses + LLM_CALL_TIMEOUT)


