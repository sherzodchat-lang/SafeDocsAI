"""Картинка первой страницы готовой колоды и её заголовок — из самого файла.

Раздел показывает сетку заказанных презентаций, и карточке нужны две вещи,
которых в строке БД исторически не было: как колода ВЫГЛЯДИТ и о ЧЁМ она.
Обе лежат в напечатанном PDF, и этот модуль их оттуда достаёт.

**Почему превью рисуется ЛЕНИВО и кэшируется на диск, а не печатается в конце
генерации.** Вариант «нарисовать один раз в конвейере» дешевле при показе, но
платит за это в трёх местах сразу. Первое: в конвейер добавляется шаг, который
может упасть — а падает он в самом конце семиминутной работы, когда колода уже
собрана, и превратить этот отказ в отказ ЗАКАЗА нельзя, то есть шаг всё равно
пришлось бы делать необязательным. Второе: у колод, собранных до этой правки,
картинки нет, и им понадобился бы отдельный проход — то есть ВТОРАЯ реализация
того же рендера, которая однажды разойдётся с первой. Третье: колода, которую
никто ни разу не открыл, платит за превью всё равно.

Ленивый рендер с кэшем на диске снимает все три: путь один и тот же для старых
и новых колод (никакой миграции), конвейера он не касается вовсе, а стоит
двести миллисекунд один раз на колоду — и только на ту, которую действительно
показали. Цена — задержка на первом показе карточки; клиент на это время
рисует крутящийся индикатор, ровно как на превью шаблона.

Кэш лежит РЯДОМ с колодой (`<файл>.preview.png`), а не в отдельном каталоге:
так удаление презентации убирает картинку тем же куском кода, что и файл, и
осиротевших превью не остаётся. Свежесть проверяется по времени изменения:
картинка старше своего PDF считается протухшей и перерисовывается. В норме это
не случается никогда (файл колоды пишется один раз и больше не меняется, а
повторный заказ — это новая строка с новым id), но две операции stat стоят
дешевле, чем один случай молча показанной чужой картинки.

**Заголовок берётся из метаданных PDF, а не разбором текста страницы.** Chrome
пишет в /Title то, что стояло в <title> напечатанной страницы, а туда рендерер
кладёт ровно plan.title — заголовок, сформулированный моделью по содержимому.
То есть это не догадка по внешнему виду титульного слайда, а тот же самый
заголовок, просто доехавший до нас через файл. Именно поэтому им можно
заполнять колонку title у колод, созданных до её появления: другого источника
для них нет, а этот — настоящий.
"""

import logging
import os
import uuid

import fitz  # PyMuPDF

from app.modules.presentations.llm_schemas import PLAN_TITLE_MAX_CHARS

logger = logging.getLogger(__name__)

# Расширение, которое умеет читать этот модуль. Колоды прежнего рендерера лежат
# в .pptx, и распаковывать их ради картинки нечем: fitz таких файлов не знает.
# Такая колода остаётся полностью рабочей (скачивается ровно как раньше), у неё
# просто нет превью — и клиент показывает ту же заглушку, что у шаблона без
# картинки.
RENDERABLE_SUFFIX = ".pdf"

# Суффикс кэша. Приписывается к ПОЛНОМУ имени файла колоды, а не заменяет
# расширение: `presentation_20.pdf.preview.png` невозможно спутать с самой
# колодой ни человеку, ни коду, который ищет на диске файлы презентаций.
CARD_PREVIEW_SUFFIX = ".preview.png"

# Ширина картинки в пикселях. Карточка в сетке — опознавательный знак шириной
# около 200 CSS-пикселей, поэтому 640 — это примерно тройная плотность: хватает
# и экранам Retina, и просмотру карточки крупнее. Больше брать незачем: страница
# колоды печатается 960x540 pt, и на 640 px её титул уже читается, а каждый
# лишний множитель — это байты в сети на КАЖДОЙ карточке сетки.
CARD_PREVIEW_WIDTH = 640

CARD_PREVIEW_MEDIA_TYPE = "image/png"


def card_preview_path(file_path: str) -> str:
    """Путь кэшированной картинки для файла колоды."""
    return f"{file_path}{CARD_PREVIEW_SUFFIX}"


def _is_fresh(preview_path: str, file_path: str) -> bool:
    """Картинка существует и не старше своей колоды."""
    try:
        return os.path.getmtime(preview_path) >= os.path.getmtime(file_path)
    except OSError:
        return False


def ensure_card_preview(file_path: str) -> str | None:
    """Путь к картинке первой страницы; при необходимости — нарисовать её.

    None означает «картинки не будет»: файл не PDF, не читается или пуст.
    Это не ошибка сервера и не отсутствие колоды — вызывающий обязан ответить
    отсутствием ИМЕННО ПРЕВЬЮ, а не отсутствием презентации.

    Функция СИНХРОННАЯ и блокирующая (декодирование страницы — работа
    процессора, около двухсот миллисекунд на колоду), поэтому в обработчике
    её место — run_in_threadpool, как и у любого другого рендера в разделе.

    Запись атомарна: картинка собирается во временный файл В ТОМ ЖЕ каталоге и
    ставится на место через os.replace. Иначе два одновременных запроса за
    одной и той же карточкой (а сетка запрашивает их пачкой) могли бы показать
    друг другу наполовину записанный PNG.
    """
    if os.path.splitext(file_path)[1].lower() != RENDERABLE_SUFFIX:
        return None

    preview_path = card_preview_path(file_path)
    if _is_fresh(preview_path, file_path):
        return preview_path

    temp_path = f"{preview_path}.tmp-{uuid.uuid4().hex}"
    try:
        with fitz.open(file_path) as document:
            if document.page_count < 1:
                logger.warning("Presentation file %s has no pages", file_path)
                return None
            page = document[0]
            # Масштаб считается от ШИРИНЫ страницы, а не задаётся числом dpi:
            # ширина картинки — это то, что видно в карточке, и она обязана
            # быть одинаковой у всех колод, какого бы формата ни была страница.
            zoom = CARD_PREVIEW_WIDTH / page.rect.width
            pixmap = page.get_pixmap(matrix=fitz.Matrix(zoom, zoom))
            # Формат назван явно: PyMuPDF выводит его из РАСШИРЕНИЯ имени, а у
            # временного файла оно случайное (.tmp-<hex>) — без output он
            # отказал бы «Image format tmp-... not in (...)».
            pixmap.save(temp_path, output="png")
        os.replace(temp_path, preview_path)
        return preview_path
    except Exception as exc:  # noqa: BLE001
        # Битый или недочитанный PDF не должен ронять показ сетки: у карточки
        # просто не будет картинки. WARNING, а не ERROR: файл на диске цел
        # ровно настолько, насколько его напечатали, и чинить тут нечего.
        logger.warning("Could not render preview of %s: %s", file_path, exc)
        return None
    finally:
        if os.path.exists(temp_path):
            try:
                os.remove(temp_path)
            except OSError:  # pragma: no cover - каталог мог исчезнуть целиком
                logger.warning("Failed to remove temporary file %s", temp_path)


def remove_card_preview(file_path: str) -> None:
    """Убрать кэш вслед за удалённой колодой. Молча, если его и не было."""
    try:
        os.remove(card_preview_path(file_path))
    except FileNotFoundError:
        pass
    except OSError as exc:
        logger.warning(
            "Could not remove cached preview of %s: %s", file_path, exc
        )


def read_stored_title(file_path: str) -> str | None:
    """Заголовок колоды из метаданных PDF (/Title), обрезанный по пределу схемы.

    Обрезка ровно по PLAN_TITLE_MAX_CHARS — тому же пределу, которым схема
    плана ограничивает заголовок при генерации. Колонка обязана иметь одну
    границу длины, а не две: иначе восстановленный из файла заголовок оказался
    бы длиннее, чем разрешено родившемуся заново.
    """
    if os.path.splitext(file_path)[1].lower() != RENDERABLE_SUFFIX:
        return None
    try:
        with fitz.open(file_path) as document:
            title = str((document.metadata or {}).get("title") or "").strip()
    except Exception as exc:  # noqa: BLE001
        logger.warning("Could not read title of %s: %s", file_path, exc)
        return None
    return title[:PLAN_TITLE_MAX_CHARS] or None
